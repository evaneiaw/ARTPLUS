// ExportMarksFocus.java - focused export for DocumentMarks.dll trim/cut mark analysis.
// Emits: target functions (signature, callers, callees, string refs), strings of interest
// with xref->function, and RTTI/vtable symbols.
// Run: analyzeHeadless <proj> <name> -process <prog> -noanalysis
//      -scriptPath "H:\Desktop\ArtPlus\tools\ghidra_analysis\ghidra_scripts"
//      -postScript ExportMarksFocus.java

import ghidra.app.script.GhidraScript;
import ghidra.program.model.address.Address;
import ghidra.program.model.address.AddressSetView;
import ghidra.program.model.listing.Data;
import ghidra.program.model.listing.Function;
import ghidra.program.model.listing.FunctionIterator;
import ghidra.program.model.listing.Instruction;
import ghidra.program.model.listing.InstructionIterator;
import ghidra.program.model.listing.Listing;
import ghidra.program.model.mem.Memory;
import ghidra.program.model.mem.MemoryBlock;
import ghidra.program.model.symbol.Reference;
import ghidra.program.model.symbol.ReferenceManager;
import ghidra.program.model.symbol.Symbol;
import ghidra.program.model.symbol.SymbolIterator;
import ghidra.program.model.symbol.SymbolTable;
import java.io.File;
import java.io.FileWriter;
import java.io.PrintWriter;
import java.util.ArrayList;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.Set;
import java.util.regex.Pattern;

public class ExportMarksFocus extends GhidraScript {

    private static final Pattern TARGET_FUNC = Pattern.compile(
        "(?i)(ApplyMarkSet|ApplyRelevantMarkSets|ApplyExtraMarkSet|ApplyMarksFromSet|" +
        "CopyMarksToPage|PrepareMarksCache|RecreateLoadedMarks|ReloadExpandedMarks|" +
        "MakeFormsFromMarks|MakeAllMarksOnPageStatic|CreateMarkName|CreateFromSelectionAction|" +
        "MarkSet|GetMarkTypeFromPDFPlusKey)");

    private static final Pattern TARGET_STRING = Pattern.compile(
        "(?i)(cut ?mark|trim ?box|trim|offset|DM-CutMark|PDFPlusCutMark|CutMark)");

    private PrintWriter out;

    @Override
    protected void run() throws Exception {
        String progName = currentProgram.getName();
        File outDir = new File("H:/Desktop/ArtPlus/rag/ghidra/exports/" + progName);
        outDir.mkdirs();
        File f = new File(outDir, "marks_focus.txt");
        out = new PrintWriter(new FileWriter(f));

        out.println("# program: " + progName);
        out.println("# image base: " + currentProgram.getImageBase());
        out.println("# generated by ExportMarksFocus.java");
        out.println();

        dumpTargetFunctions();
        dumpStrings();
        dumpRtti();
        out.close();
        println("Wrote " + f.getAbsolutePath());
    }

    private void dumpTargetFunctions() throws Exception {
        out.println("=== TARGET FUNCTIONS ===");
        FunctionIterator it = currentProgram.getFunctionManager().getFunctions(true);
        int n = 0;
        while (it.hasNext() && !monitor.isCancelled()) {
            Function fn = it.next();
            String name = fn.getName();
            String full = fn.getName(true);
            boolean isCut = full != null && (full.contains("CutMark") || full.contains("TrimSymbol"));
            if (!isCut && (name == null || !TARGET_FUNC.matcher(name).find())) {
                continue;
            }
            n++;
            out.println();
            out.println("FUNC " + fn.getEntryPoint() + " " + name);
            out.println("  signature: " + fn.getSignature().getPrototypeString());
            out.println("  namespace: " + fn.getParentNamespace().getName(true));
            out.println("  thunk: " + fn.isThunk());

            List<String> callers = new ArrayList<>();
            ReferenceManager rm = currentProgram.getReferenceManager();
            for (Reference r : rm.getReferencesTo(fn.getEntryPoint())) {
                Function caller = getFunctionContaining(r.getFromAddress());
                String cn = caller != null ? caller.getName() + "@" + caller.getEntryPoint() : "??";
                String entry = r.getFromAddress() + " in " + cn;
                if (!callers.contains(entry)) {
                    callers.add(entry);
                }
            }
            out.println("  callers (" + callers.size() + "):");
            for (String c : callers) {
                out.println("    <- " + c);
            }

            Set<Function> callees = fn.getCalledFunctions(monitor);
            out.println("  callees (" + callees.size() + "):");
            for (Function c : callees) {
                out.println("    -> " + c.getEntryPoint() + " " + c.getName());
            }

            out.println("  refs from body:");
            AddressSetView body = fn.getBody();
            Listing listing = currentProgram.getListing();
            InstructionIterator insIt = listing.getInstructions(body, true);
            Set<String> seen = new LinkedHashSet<>();
            while (insIt.hasNext()) {
                Instruction ins = insIt.next();
                for (Reference r : ins.getReferencesFrom()) {
                    Address to = r.getToAddress();
                    String desc = describeTarget(to);
                    if (desc != null) {
                        String line = "    " + ins.getAddress() + " -> " + to + " " + desc;
                        if (seen.add(line)) {
                            out.println(line);
                        }
                    }
                }
            }
        }
        out.println();
        out.println("# target function count: " + n);
    }

    private String describeTarget(Address to) {
        String sym = "";
        Symbol s = currentProgram.getSymbolTable().getPrimarySymbol(to);
        if (s != null) {
            sym = s.getName(true);
        }
        Data d = currentProgram.getListing().getDataAt(to);
        String val = null;
        if (d != null && d.getValue() != null) {
            val = d.getValue().toString();
            if (val.length() > 160) {
                val = val.substring(0, 160) + "...";
            }
            val = val.replace("\n", "\\n").replace("\r", "");
        }
        if (val != null) {
            return "[string] \"" + val + "\"" + (sym.isEmpty() ? "" : " sym=" + sym);
        }
        if (!sym.isEmpty()) {
            return "sym=" + sym;
        }
        return null;
    }

    private void dumpStrings() throws Exception {
        out.println();
        out.println("=== STRINGS OF INTEREST (with xrefs) ===");
        ReferenceManager rm = currentProgram.getReferenceManager();
        Listing listing = currentProgram.getListing();

        MemoryBlock[] blocks = currentProgram.getMemory().getBlocks();
        int count = 0;
        for (MemoryBlock b : blocks) {
            if (!b.isInitialized() || b.isExecute()) {
                continue;
            }
            ghidra.program.model.listing.DataIterator di = listing.getDefinedData(b.getStart(), true);
            while (di.hasNext() && !monitor.isCancelled()) {
                Data d = di.next();
                Address a = d.getAddress();
                if (!b.contains(a)) {
                    break;
                }
                if (!d.hasStringValue()) {
                    continue;
                }
                Object v = d.getValue();
                if (v == null) {
                    continue;
                }
                String str = v.toString();
                if (str.length() < 3 || !TARGET_STRING.matcher(str).find()) {
                    continue;
                }
                count++;
                String clean = str.replace("\n", "\\n").replace("\r", "");
                if (clean.length() > 200) {
                    clean = clean.substring(0, 200) + "...";
                }
                out.println("STR " + a + " \"" + clean + "\"");
                for (Reference r : rm.getReferencesTo(a)) {
                    Address from = r.getFromAddress();
                    Function fn = getFunctionContaining(from);
                    String fname = fn != null ? fn.getName() + "@" + fn.getEntryPoint() : "<no function>";
                    out.println("    <- " + from + "  " + fname);
                }
            }
        }
        out.println("# string hits: " + count);
    }

    private void dumpRtti() throws Exception {
        out.println();
        out.println("=== RTTI / VTABLE SYMBOLS ===");
        SymbolTable st = currentProgram.getSymbolTable();
        SymbolIterator syms = st.getAllSymbols(true);
        while (syms.hasNext() && !monitor.isCancelled()) {
            Symbol s = syms.next();
            String name = s.getName();
            if (!name.startsWith("??_R")) {
                continue;
            }
            if (!name.contains("CutMark") && !name.contains("TrimSymbol")) {
                continue;
            }
            out.println("RTTI " + s.getAddress() + " " + name);
        }

        out.println();
        out.println("=== VTABLES ===");
        Memory mem = currentProgram.getMemory();
        SymbolIterator all = st.getAllSymbols(true);
        java.util.List<Symbol> vtSyms = new java.util.ArrayList<>();
        while (all.hasNext() && !monitor.isCancelled()) {
            Symbol s = all.next();
            String n = s.getName();
            if (n != null && n.startsWith("??_7") && n.contains("CutMark")) {
                vtSyms.add(s);
            }
        }
        for (Symbol vs : vtSyms) {
            out.println("VTABLE " + vs.getAddress() + " " + vs.getName());
            Address p = vs.getAddress();
            // RTTI: the 8 bytes before the vtable hold the Complete Object Locator pointer.
            try {
                long col = mem.getLong(p.subtract(8));
                Address colAddr = p.getNewAddress(col);
                out.println("  COL " + colAddr);
                long sig = mem.getInt(colAddr) & 0xffffffffL;
                long off = mem.getInt(colAddr.add(4)) & 0xffffffffL;
                long cd = mem.getInt(colAddr.add(8)) & 0xffffffffL;
                long td = mem.getInt(colAddr.add(12)) & 0xffffffffL;
                out.println("    signature=" + sig + " offset=" + off + " cdOffset=" + cd);
                Address tdAddr = p.getNewAddress(td);
                Data tdd = currentProgram.getListing().getDataAt(tdAddr);
                out.println("    typeDescriptor=" + tdAddr
                    + (tdd != null && tdd.getValue() != null ? " \"" + tdd.getValue() + "\"" : ""));
            }
            catch (Exception e) {
                out.println("  COL unreadable: " + e.getMessage());
            }
            for (int i = 0; i < 80; i++) {
                Address slot = p.add((long) i * 8L);
                long val;
                try {
                    val = mem.getLong(slot);
                }
                catch (Exception e) {
                    out.println("    [unreadable at " + slot + "]");
                    break;
                }
                if (val == 0) {
                    break;
                }
                Address target;
                try {
                    target = slot.getNewAddress(val);
                }
                catch (Exception e) {
                    out.println("    [" + i + "] invalid pointer " + Long.toHexString(val));
                    break;
                }
                Function tf = getFunctionAt(target);
                String tn = tf != null ? tf.getName(true) : "?";
                out.println("    [" + i + "] " + target + " " + tn);
                if (tf == null) {
                    break;
                }
            }
        }
        out.println("# vtables: " + vtSyms.size());
    }
}
